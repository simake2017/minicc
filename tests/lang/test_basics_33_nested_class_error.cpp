// =============================================================================
// 测试（错误用例）：限定名指向不存在的嵌套类成员
// =============================================================================
// 理论点：
//   · [basic.lookup.qual]：限定名 `A::C` 的限定者 A 解析成【类型】后，
//     成员名 C 必须在 A 的成员表（嵌套类 + 类内类型别名）里找 ——
//     找不到就是 ill-formed，诊断指向【根因】（哪个类的哪个成员），
//     而不是笼统的"未知类型名"。
//   · ★ 这条判据是 Stage 3 批 4 顺带修好的：此前 `A::C` 走"名字串查符号表"
//     这条路，落空后只报 "unknown type name 'A::C'" —— 指向的是【拼出来的串】
//     而不是"类 A 里没有成员 C"，排查时容易误导。
// 预期行为：rc=1，报错文案
//   no type named 'C' in 'A'
// 对照 clang：clang++-18 -std=c++20 同样 rc=1，报错逐字相同（探针校准）。
// =============================================================================

struct A {
    struct B { int v; };     // 只有嵌套类 B，没有 C
};

int main() {
    A::C c;                  // ✗ A 里没有名为 C 的成员类型
    return 0;
}
