// =============================================================================
// 测试（错误用例）：类外定义的限定者不是类
// =============================================================================
// 理论点：
//   · `int x::count = 3;` 的 `x` 必须是类（本实现语境）、命名空间或枚举 ——
//     变量名不能做限定者。校验按全名查类注册表（m_classDecls），落空即拒。
// 预期行为：rc=1，报错文案
//   'x' is not a class, namespace, or enumeration
// 对照 clang：clang++-18 -std=c++20 同样 rc=1，报错逐字相同（探针校准）。
// 回归背景（docs/BUGS.md B33）：随静态数据成员特性新增，负向用例防回归。
// =============================================================================

int x;

int x::count = 3;   // ✗ x 是变量，不是类/命名空间/枚举

int main() { return 0; }
