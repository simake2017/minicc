// =============================================================================
// 测试（错误用例）：类外定义了类里没声明过的静态成员
// =============================================================================
// 理论点：
//   · 类外定义 `int A::other = 3;` 的前提是类 A 声明过这个 static 成员
//     （staticDataMembers 是权威声明表）——没声明过即 ill-formed。
//   · 校验顺序在符号定义之前：这条拦截先于 "存储" 概念存在。
// 预期行为：rc=1，报错文案
//   no member named 'other' in 'A'
// 对照 clang：clang++-18 -std=c++20 同样 rc=1，报错逐字相同（探针校准）。
// 回归背景（docs/BUGS.md B31）：随静态数据成员特性新增，负向用例防回归。
// =============================================================================

struct A {
    static int count;
};

int A::other = 3;   // ✗ A 没声明过 other

int main() { return 0; }
