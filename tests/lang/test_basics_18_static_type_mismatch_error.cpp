// =============================================================================
// 测试（错误用例）：类外定义的类型与类内声明不一致
// =============================================================================
// 理论点：
//   · 类外定义必须与类内声明是【同一类型】 —— 不是"可隐式转换"即可：
//     `long A::count` 对声明 `static int count` 是 ill-formed。
//     ★ 判据用 equals 而非 typeCompatible：后者把 long/int 判成兼容
//     （静默放行，负向全绿掩盖缺陷 —— 探针校准时实测抓到的）。
// 预期行为：rc=1，报错文案
//   redefinition of 'count' with a different type: 'long' vs 'int'
// 对照 clang：clang++-18 -std=c++20 同样 rc=1，报错逐字相同（探针校准）。
// 回归背景（docs/BUGS.md B33）：随静态数据成员特性新增，负向用例防回归。
// =============================================================================

struct A {
    static int count;
};

long A::count = 3;   // ✗ 声明是 int，定义是 long

int main() { return 0; }
