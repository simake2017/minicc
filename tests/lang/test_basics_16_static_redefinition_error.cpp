// =============================================================================
// 测试（错误用例）：静态数据成员的重复类外定义（ODR）
// =============================================================================
// 理论点：
//   · ODR（[basic.def.odr]）：一个静态数据成员在全程序只许一个定义。
//     C++ 通常要到链接期才爆重复符号；本实现在语义期就拦下（编译期报错
//     优于链接期报错，判据单点：m_definedStaticMembers 登记簿）。
// 预期行为：rc=1，报错文案
//   redefinition of 'count'
// 对照 clang：clang++-18 -std=c++20 同样 rc=1，报错逐字相同（探针校准）。
// 回归背景（docs/BUGS.md B33）：随静态数据成员特性新增，负向用例防回归。
// =============================================================================

struct A {
    static int count;
};

int A::count = 3;
int A::count = 4;   // ✗ 第二个定义

int main() { return 0; }
