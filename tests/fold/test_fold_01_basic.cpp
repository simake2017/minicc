// =============================================================================
// 测试：常量折叠（主线 D 第一批 —— Sema 层折叠 + 死分支消除）
// =============================================================================
// 预期行为：
//   全常量表达式在编译期折成单个字面量（日志可见 [fold] 行），运行期直接
//   拿到结果；含变量的表达式【不折】（原样保留到代码生成）；常量条件的
//   三元表达式折成选定分支（死分支消除）；除零【不折】（UB 不替程序决定）。
//   全部检查点通过返回 0，任一失败返回该检查点编号。
//
// 考察理论点：
//   · 常量折叠 = 编译器最古老优化的内核：操作数全为字面量的表达式树
//     在编译期归约为一个字面量（对照 clang Sema 层随手折 +
//     InstCombine 兜底；求值语义裁判见 lib/AST/ExprConstant.cpp）。
//   · 折叠-传播交替：折出 5 后外层 5 * 2 又能折 ⇒ 自底向上递归折。
//   · 死分支消除的最小形态：`true ? a : b` 中 b 支永不生成代码
//     （对照 clang CodeGen 对恒定条件只发选中分支）。
//   · 诚实原则：折不动的（除零、含变量）原样保留 —— 折叠只许变快，
//     不许变语义。
// =============================================================================

int g_side_effect = 0;
int touch() { g_side_effect = g_side_effect + 1; return 7; }

int main() {
    // 1. 基本折叠：2 + 3*4 ⇒ 14（乘法先于加法，自底向上：3*4 → 12，2+12 → 14）
    int a = 2 + 3 * 4;
    if (a != 14) return 1;

    // 2. 折叠-传播交替：(2 + 3) * (4 + 6) ⇒ 5 * 10 ⇒ 50
    int b = (2 + 3) * (4 + 6);
    if (b != 50) return 2;

    // 3. 比较与逻辑折叠成 bool 字面量：(3 > 2) && (1 == 1) ⇒ true ⇒ 1
    bool c = (3 > 2) && (1 == 1);
    if (!c) return 3;

    // 4. 常量三元 = 死分支消除：假支的 touch() 永不执行
    int d = true ? 11 : touch();
    if (d != 11) return 4;
    if (g_side_effect != 0) return 5;   // 死分支被执行了 ⇒ 消除失败

    // 5. 一元折叠：-(2 + 3) ⇒ -5
    int e = -(2 + 3);
    if (e != -5) return 6;

    // 6. 含变量的表达式【不折】：x + 1 原样保留（日志里无 [fold] 行）
    int x = 10;
    int f = x + 1;
    if (f != 11) return 7;

    // 7. 混合：常量部分折到底、变量部分保留 —— (2 * 3) + x ⇒ 6 + x
    int g = 2 * 3 + x;
    if (g != 16) return 8;

    return 0;
}
