// =============================================================================
// 测试：do-while 循环 + 逗号表达式（主线 C 二批，[stmt.do]/[expr.comma]）
// =============================================================================
// 预期行为：
//   do-while：体【先于条件执行一轮】，条件测试代码在体之后；continue
//   落条件式（同 while，与 for 的增量步不同）。
//   逗号表达式 `(a, b)`：先求 a（副作用照做），值与类型取 b。纯字面量
//   的左操作数被折叠丢弃（无副作用可消除）——`[fold] (1, 2) → 2`；
//   有副作用的左操作数（函数调用）保留到代码生成。
//   全部检查点通过返回 0，任一失败返回该检查点编号。
//
// 考察理论点：
//   · [stmt.do]：与 while 的唯一差别是测试位置（尾部 vs 头部）。
//   · [expr.comma]：优先级全语言最低；值 = 右操作数。
//   · 逗号只在【括号内】开放（调用实参表等处的 ',' 仍是分隔符 —— 不做
//     上下文区分，已知边界，docs/learn/41）。
// =============================================================================

int g_side = 0;
int touch(int v) { g_side = g_side + v; return v; }

int main() {
    // 1. do-while 体先执行：条件一开始为假也跑一轮
    int i = 100;
    do { i = i + 1; } while (i < 3);
    if (i != 101) return 1;

    // 2. 正常循环：0 → 1 → 2 → 3 出
    int j = 0;
    do { j = j + 1; } while (j < 3);
    if (j != 3) return 2;

    // 3. do-while 里的 continue 落条件式：跳过剩余体，测条件
    int k = 0;
    int sum = 0;
    do {
        k = k + 1;
        if (k == 2) continue;    // 落条件式 ⇒ k=2 那轮不加 sum
        sum = sum + k;
    } while (k < 4);
    if (sum != 8) return 3;      // 1 + 3 + 4

    // 4. 逗号表达式：副作用照做，值取右操作数
    int c = (touch(5), 42);
    if (c != 42) return 4;
    if (g_side != 5) return 5;

    // 5. 链式逗号：(touch(1), touch(2), 7) 依次执行
    int d = (touch(1), touch(2), 7);
    if (d != 7) return 6;
    if (g_side != 8) return 7;   // 5 + 1 + 2

    // 6. 纯字面量逗号折叠：`(1, 2, 3)` 值 3（左操作数无副作用，被消掉）
    int e = (1, 2, 3);
    if (e != 3) return 8;

    return 0;
}
